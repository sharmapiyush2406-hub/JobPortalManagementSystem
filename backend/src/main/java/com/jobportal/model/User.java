package com.jobportal.model;

import java.sql.Timestamp;

/**
 * User Entity Model
 * Represents Candidates and Administrators in the Job Portal.
 */
public class User {
    private int userId;
    private String name;
    private String email;
    private transient String password; // Not serialized to JSON for security
    private String role; // "CANDIDATE" or "ADMIN"
    private Timestamp createdAt;

    public User() {
    }

    public User(int userId, String name, String email, String password, String role, Timestamp createdAt) {
        this.userId = userId;
        this.name = name;
        this.email = email;
        this.password = password;
        this.role = role;
        this.createdAt = createdAt;
    }

    public int getUserId() {
        return userId;
    }

    public void setUserId(int userId) {
        this.userId = userId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getPassword() {
        return password;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    public String getRole() {
        return role;
    }

    public void setRole(String role) {
        this.role = role;
    }

    public Timestamp getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Timestamp createdAt) {
        this.createdAt = createdAt;
    }

    public boolean isAdmin() {
        return "ADMIN".equalsIgnoreCase(this.role);
    }
}
